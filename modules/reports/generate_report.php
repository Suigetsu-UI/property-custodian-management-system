<?php

require_once "../../auth/check_auth.php";
require_once __DIR__ . "/../../includes/report_functions.php";

if ($_SERVER['REQUEST_METHOD'] === 'POST') {

    $reportType =
        trim($_POST['report_type'] ?? '');

    $generatedBy =
        trim($_POST['generated_by'] ?? '');

    if (
        !isAllowedReportType($reportType) ||
        $generatedBy === ''
    ) {
        header("Location: index.php?error=invalid_report");
        exit;
    }

    $query = http_build_query([
        'report_type' => $reportType,
        'generated_by' => $generatedBy
    ]);

    header(
        "Location: view_report.php?" . $query
    );

    exit;
}

?>

<form
    class="asset-form"
    method="POST"
    action="generate_report.php"
>

<h2>Generate New Report</h2>

<div class="form-row">

<label>Report Type</label>

<select
    name="report_type"
    required
>

<?php foreach (getAllowedReportTypes() as $reportType): ?>

<option value="<?= htmlspecialchars($reportType) ?>">
    <?= htmlspecialchars($reportType) ?>
</option>

<?php endforeach; ?>

</select>

</div>

<div class="form-row">

<label>Generated By</label>

<input
    type="text"
    name="generated_by"
    required
>

</div>

<div class="form-row">

<label>Date Generated</label>

<input
    type="date"
    value="<?= htmlspecialchars(date('Y-m-d')) ?>"
    readonly
>

</div>

<button
    type="submit"
    class="btn btn-primary"
>
Generate Report
</button>

</form>